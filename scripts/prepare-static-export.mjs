/**
 * Strip the server-only parts of the app so `next build` can emit a fully
 * static site (`output: "export"`) for the GitHub Pages preview.
 *
 * DESTRUCTIVE: it deletes files in place, so only ever run it on a throwaway
 * checkout — that is what the Pages workflow does. It refuses to run unless
 * FORCE_STATIC_EXPORT=1 is set, so a stray local run cannot wipe your tree.
 *
 * What the preview keeps: the whole marketing and SEO surface (home, hotels,
 * things to do, destinations, route pages, airports, airlines, guides, help,
 * legal) and the entire WhatsApp search flow, which runs in the browser and
 * needs no server at all. What it drops: anything that needs a database or an
 * API route — fare results, price lock, checkout, accounts, admin, the contact
 * form and price alerts. Deep links that would have pointed at those pages
 * become WhatsApp links instead (see buildSearchUrl).
 */
import fs from "node:fs";
import path from "node:path";

if (process.env.FORCE_STATIC_EXPORT !== "1") {
  console.error("Refusing to run: set FORCE_STATIC_EXPORT=1 (this deletes files).");
  process.exit(1);
}

const root = process.cwd();

/** Routes that cannot exist in a static export. */
const REMOVE = [
  "src/app/api",
  "src/app/flights/search",
  "src/app/lock",
  "src/app/book",
  "src/app/booking",
  "src/app/account",
  "src/app/admin",
  "src/app/contact",
  "src/app/price-alerts",
  // Proxy/middleware and route handlers have no runtime on Pages.
  "src/proxy.ts",
  "src/middleware.ts",
  "src/app/robots.ts",
  "src/app/sitemap.ts",
  "src/app/manifest.ts",
];

for (const rel of REMOVE) {
  const abs = path.join(root, rel);
  if (!fs.existsSync(abs)) continue;
  fs.rmSync(abs, { recursive: true, force: true });
  console.log(`removed ${rel}`);
}

// Route config that a static export cannot honour: every remaining page has to
// be prerendered, and unknown slugs must 404 rather than render on demand.
function rewriteRouteConfig(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      rewriteRouteConfig(abs);
    } else if (/\.(tsx|ts)$/.test(entry.name)) {
      const before = fs.readFileSync(abs, "utf8");
      const after = before.replace(/export const dynamic = "force-dynamic";/g, 'export const dynamic = "force-static";').replace(/export const dynamicParams = true;/g, "export const dynamicParams = false;");
      if (after !== before) {
        fs.writeFileSync(abs, after);
        console.log(`rewrote route config in ${path.relative(root, abs)}`);
      }
    }
  }
}
rewriteRouteConfig(path.join(root, "src/app"));

// A minimal config: static export, optional base path for project pages.
const basePath = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
const config = `import type { NextConfig } from "next";

/** Generated by scripts/prepare-static-export.mjs — static preview only. */
const nextConfig: NextConfig = {
  output: "export",
  trailingSlash: true,
  reactStrictMode: true,
  poweredByHeader: false,
  images: { unoptimized: true },
${basePath ? `  basePath: "${basePath}",\n  assetPrefix: "${basePath}",\n` : ""}};

export default nextConfig;
`;
fs.writeFileSync(path.join(root, "next.config.ts"), config);
console.log(`wrote static next.config.ts${basePath ? ` (basePath ${basePath})` : ""}`);

// robots.txt and a sitemap still matter for the preview; write them flat.
const siteUrl = (process.env.NEXT_PUBLIC_SITE_URL ?? "").replace(/\/+$/, "");
fs.mkdirSync(path.join(root, "public"), { recursive: true });
fs.writeFileSync(path.join(root, "public/robots.txt"), `User-agent: *\nAllow: /\n${siteUrl ? `Sitemap: ${siteUrl}/sitemap.xml\n` : ""}`);
console.log("wrote public/robots.txt");

// app/manifest.ts is a route handler, so the preview ships a plain file instead.
fs.writeFileSync(
  path.join(root, "public/manifest.webmanifest"),
  JSON.stringify({ name: "Air1 Tickets", short_name: "Air1", start_url: `${basePath || ""}/`, display: "standalone", background_color: "#ffffff", theme_color: "#0b1d3a" }, null, 2),
);
console.log("wrote public/manifest.webmanifest");
